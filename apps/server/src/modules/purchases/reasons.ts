import type { AgentReasonCode, Decision, TransactionStatus } from '@leash/shared';

/**
 * Internal reason codes → the coarse codes agents see. Agents learn what kind
 * of outcome happened, never which threshold or detector fired.
 */
const AGENT_REASON: Record<string, AgentReasonCode> = {
  NO_ACTIVE_POLICY: 'SPENDING_PAUSED',
  SANDBOX_CEILING_EXCEEDED: 'LIMIT_EXCEEDED',
  AMOUNT_OVER_LIMIT: 'LIMIT_EXCEEDED',
  PERIOD_SPEND_LIMIT: 'LIMIT_EXCEEDED',
  PERIOD_TRANSACTION_LIMIT: 'LIMIT_EXCEEDED',
  TASK_BUDGET_EXCEEDED: 'LIMIT_EXCEEDED',
  CURRENCY_NOT_ALLOWED: 'CURRENCY_NOT_ALLOWED',
  TASK_CURRENCY_MISMATCH: 'CURRENCY_NOT_ALLOWED',
  TASK_NOT_ACTIVE: 'TASK_NOT_ACTIVE',
  MERCHANT_NOT_IN_TASK: 'MERCHANT_NOT_ALLOWED',
  MERCHANT_NOT_ALLOWED: 'MERCHANT_NOT_ALLOWED',
  MERCHANT_BLOCKED: 'MERCHANT_NOT_ALLOWED',
  MERCHANT_ARCHIVED: 'MERCHANT_NOT_ALLOWED',
  CATEGORY_NOT_ALLOWED: 'MERCHANT_NOT_ALLOWED',
  CATEGORY_BLOCKED: 'MERCHANT_NOT_ALLOWED',
  NEW_MERCHANT: 'POLICY_RULE',
  OUTSIDE_TIME_WINDOW: 'POLICY_RULE',
  DUPLICATE_PURCHASE: 'POLICY_RULE',
  INJECTION_DETECTED: 'NOT_PERMITTED',
  INTENT_MISMATCH: 'NOT_PERMITTED',
  INJECTION_SUSPECTED: 'REQUIRES_APPROVAL',
  INTENT_UNCERTAIN: 'REQUIRES_APPROVAL',
  AI_UNAVAILABLE: 'REQUIRES_APPROVAL',
  AI_SIGNALS_INVALID: 'REQUIRES_APPROVAL',
  EVALUATION_TIMEOUT: 'EVALUATION_TIMEOUT',
  APPROVAL_EXPIRED: 'APPROVAL_EXPIRED',
  AUTHORIZATION_EXPIRED: 'AUTHORIZATION_EXPIRED',
  CANCELLED: 'CANCELLED',
  HUMAN_APPROVED: 'APPROVED',
  HUMAN_REJECTED: 'REJECTED',
  // Payment failures: the agent learns only that payment failed, never why.
  PAYMENT_DECLINED: 'PAYMENT_FAILED',
  ORDER_MISMATCH: 'PAYMENT_FAILED',
  PAYEE_CHANGED: 'PAYMENT_FAILED',
  POLICY_BLOCKED_AT_CAPTURE: 'PAYMENT_FAILED',
  ORDER_VOIDED: 'PAYMENT_FAILED',
  PAYMENT_CAPTURED: 'PAID',
};

export function agentReasonCodes(
  internal: readonly string[],
  decision: Decision | null,
  status: TransactionStatus,
): AgentReasonCode[] {
  const codes = new Set<AgentReasonCode>(internal.map((c) => AGENT_REASON[c] ?? 'POLICY_RULE'));
  if (decision === 'ESCALATE' && status === 'PENDING_APPROVAL') codes.add('REQUIRES_APPROVAL');
  return [...codes];
}
