import type { PolicyVersionDto, SimulationResponse } from '@leash/shared';
import { useState, type FormEvent } from 'react';
import { Link, useNavigate, useParams } from 'react-router';
import {
  useConfirmPolicy,
  useDuplicateVersion,
  usePolicyVersion,
  useRejectDraft,
  useSimulatePurchase,
  useUpdateDraft,
  useValidatePolicy,
} from '../../api/policies';
import { useTasks } from '../../api/tasks';
import { Button } from '../../components/ui/Button';
import { Dialog } from '../../components/ui/Dialog';
import { ErrorMessage, Loading } from '../../components/ui/Feedback';
import { Field, Input, Select, Textarea } from '../../components/ui/Form';
import { PageHeader, Panel } from '../../components/ui/Layout';
import { DecisionPill, LifecycleStatus, StatusPill } from '../../components/ui/StatusPill';
import { formatDateTime } from '../../lib/format';
import { PolicyRules } from './PolicyRules';

export function PolicyReviewPage() {
  const { id = '' } = useParams();
  const version = usePolicyVersion(id);
  if (version.isPending) return <Loading />;
  if (version.isError) return <ErrorMessage error={version.error} />;
  return <PolicyReview policy={version.data} />;
}

function PolicyReview({ policy }: { policy: PolicyVersionDto }) {
  const isDraft = policy.status === 'DRAFT';
  const [acknowledged, setAcknowledged] = useState(false);
  const [confirming, setConfirming] = useState(false);
  const reject = useRejectDraft(policy.id);
  const duplicate = useDuplicateVersion();
  const navigate = useNavigate();
  const needsAck = policy.unmappedClauses.length > 0;

  return (
    <div className="space-y-6">
      <p className="text-sm">
        <Link to="/policies" className="text-slate-600 hover:text-slate-900">
          ← Spending policy
        </Link>
      </p>
      <PageHeader
        title={
          isDraft ? `Review draft · version ${policy.version}` : `Policy version ${policy.version}`
        }
        description={
          isDraft
            ? 'Check that the rules below say exactly what you meant. Nothing is enforced until you confirm.'
            : `Created ${formatDateTime(policy.createdAt)}${policy.confirmedAt ? ` · confirmed ${formatDateTime(policy.confirmedAt)}` : ''}`
        }
        actions={<LifecycleStatus status={policy.status} />}
      />

      <Panel title="What you wrote">
        <p className="whitespace-pre-wrap break-words px-5 py-4 text-sm text-slate-800">
          {policy.sourceText}
        </p>
      </Panel>

      <Panel title="What Leash will enforce">
        <div className="px-5 py-4">
          <PolicyRules policy={policy} />
          <p className="mt-4 text-xs text-slate-500">
            This summary is generated by Leash’s own code from the exact rules below — not written
            by the AI — so it always matches what is enforced. Periods use{' '}
            {policy.compiledRules.timezone}; amounts are in {policy.compiledRules.currency}.
          </p>
        </div>
      </Panel>

      {needsAck && (
        <section className="rounded-xl bg-amber-50 px-5 py-4 text-sm text-amber-950 ring-1 ring-inset ring-amber-600/20">
          <h2 className="font-semibold">Not enforced — Leash could not express these as rules</h2>
          <ul className="mt-2 space-y-1.5">
            {policy.unmappedClauses.map((c) => (
              <li key={c.text}>
                <span className="font-medium">“{c.text}”</span> — {c.reason}
              </li>
            ))}
          </ul>
          {isDraft && (
            <label className="mt-3 flex items-center gap-2 font-medium">
              <input
                type="checkbox"
                checked={acknowledged}
                onChange={(e) => setAcknowledged(e.target.checked)}
              />
              I understand these will not be enforced
            </label>
          )}
        </section>
      )}

      {policy.assumptions.length > 0 && (
        <Panel title="How your wording was interpreted">
          <ul className="list-disc space-y-1 px-9 py-4 text-sm text-slate-700">
            {policy.assumptions.map((a) => (
              <li key={a}>{a}</li>
            ))}
          </ul>
        </Panel>
      )}

      <SimulatorPanel policy={policy} />
      <JsonPanel policy={policy} />

      <p className="text-xs text-slate-500">
        Translated by <span className="font-mono">{policy.compilerModel}</span> (
        {policy.promptVersion}){policy.editedManually && ', then edited by hand'} · rules hash{' '}
        <span className="font-mono">{policy.rulesHash.slice(0, 12)}…</span>
      </p>

      <ErrorMessage error={reject.error ?? duplicate.error} />
      <div className="flex flex-wrap gap-2 border-t border-slate-200 pt-4">
        {isDraft ? (
          <>
            <Button disabled={needsAck && !acknowledged} onClick={() => setConfirming(true)}>
              Confirm and enforce
            </Button>
            <Button
              variant="ghost"
              disabled={reject.isPending}
              onClick={() => reject.mutate(undefined, { onSuccess: () => navigate('/policies') })}
            >
              Discard draft
            </Button>
          </>
        ) : (
          <Button
            variant="secondary"
            disabled={duplicate.isPending}
            onClick={() =>
              duplicate.mutate(policy.id, {
                onSuccess: (d) => navigate(`/policies/versions/${d.id}`),
              })
            }
          >
            Copy into a new draft
          </Button>
        )}
      </div>

      {confirming && (
        <ConfirmDialog
          policy={policy}
          acknowledgeUnmapped={acknowledged}
          onClose={() => setConfirming(false)}
          onDone={() => navigate('/policies')}
        />
      )}
    </div>
  );
}

function ConfirmDialog({
  policy,
  acknowledgeUnmapped,
  onClose,
  onDone,
}: {
  policy: PolicyVersionDto;
  acknowledgeUnmapped: boolean;
  onClose: () => void;
  onDone: () => void;
}) {
  const confirm = useConfirmPolicy(policy.id);
  const [password, setPassword] = useState('');
  function submit(e: FormEvent) {
    e.preventDefault();
    // rulesHash pins the confirmation to exactly the version on screen.
    confirm.mutate(
      { rulesHash: policy.rulesHash, acknowledgeUnmapped, password },
      { onSuccess: onDone },
    );
  }
  return (
    <Dialog open onClose={onClose} title={`Enforce version ${policy.version}?`}>
      <form onSubmit={submit} className="space-y-4">
        <p className="text-sm text-slate-700">
          From now on, every purchase by every agent is checked against these{' '}
          {policy.rendered.length} rule
          {policy.rendered.length === 1 ? '' : 's'}. Your current policy (if any) is replaced.
        </p>
        <ErrorMessage error={confirm.error} />
        <Field label="Confirm with your password">
          {(id) => (
            <Input
              id={id}
              type="password"
              autoComplete="current-password"
              required
              value={password}
              onChange={(e) => setPassword(e.target.value)}
            />
          )}
        </Field>
        <div className="flex justify-end gap-2">
          <Button variant="ghost" onClick={onClose}>
            Cancel
          </Button>
          <Button type="submit" disabled={confirm.isPending}>
            Confirm and enforce
          </Button>
        </div>
      </form>
    </Dialog>
  );
}

function JsonPanel({ policy }: { policy: PolicyVersionDto }) {
  const isDraft = policy.status === 'DRAFT';
  const [editing, setEditing] = useState(false);
  const [text, setText] = useState(() => JSON.stringify(policy.compiledRules, null, 2));
  const [parseError, setParseError] = useState<string | null>(null);
  const validate = useValidatePolicy();
  const save = useUpdateDraft(policy.id);

  function parse(): unknown {
    try {
      setParseError(null);
      return JSON.parse(text);
    } catch (e) {
      setParseError(`Not valid JSON: ${(e as Error).message}`);
      return undefined;
    }
  }

  return (
    <Panel
      title="Exact rules (JSON)"
      actions={
        isDraft && !editing ? (
          <Button size="sm" variant="secondary" onClick={() => setEditing(true)}>
            Edit JSON
          </Button>
        ) : undefined
      }
    >
      <div className="space-y-3 px-5 py-4">
        {editing ? (
          <>
            <Textarea
              aria-label="Policy JSON"
              rows={14}
              spellCheck={false}
              className="font-mono text-xs"
              value={text}
              onChange={(e) => {
                setText(e.target.value);
                validate.reset();
              }}
            />
            {parseError && <p className="text-xs text-rose-600">{parseError}</p>}
            {validate.data && !validate.data.valid && (
              <ul className="list-disc pl-5 text-xs text-rose-700">
                {validate.data.errors.map((e) => (
                  <li key={`${e.path}:${e.message}`}>
                    <span className="font-mono">{e.path}</span>: {e.message}
                  </li>
                ))}
              </ul>
            )}
            {validate.data?.valid && (
              <div className="rounded-md bg-emerald-50 px-3 py-2 text-xs text-emerald-900 ring-1 ring-inset ring-emerald-600/20">
                Valid. This would enforce:
                <ul className="mt-1 list-disc pl-5">
                  {validate.data.rendered.map((r) => (
                    <li key={r.id}>{r.text}</li>
                  ))}
                </ul>
              </div>
            )}
            <ErrorMessage error={validate.error ?? save.error} />
            <div className="flex gap-2">
              <Button
                size="sm"
                variant="secondary"
                onClick={() => {
                  const value = parse();
                  if (value !== undefined) validate.mutate(value);
                }}
              >
                Check
              </Button>
              <Button
                size="sm"
                disabled={save.isPending}
                onClick={() => {
                  const value = parse();
                  if (value !== undefined)
                    save.mutate(value, { onSuccess: () => setEditing(false) });
                }}
              >
                Save draft
              </Button>
              <Button size="sm" variant="ghost" onClick={() => setEditing(false)}>
                Cancel
              </Button>
            </div>
          </>
        ) : (
          <pre className="max-h-80 overflow-auto rounded-md bg-slate-50 p-3 text-xs text-slate-800 ring-1 ring-inset ring-slate-200">
            {JSON.stringify(policy.compiledRules, null, 2)}
          </pre>
        )}
      </div>
    </Panel>
  );
}

function SimulatorPanel({ policy }: { policy: PolicyVersionDto }) {
  const tasks = useTasks('ACTIVE');
  const simulate = useSimulatePurchase();
  const [taskId, setTaskId] = useState('');
  const [merchantId, setMerchantId] = useState('');
  const [amount, setAmount] = useState('');
  const task = tasks.data?.find((t) => t.id === (taskId || tasks.data?.[0]?.id));
  const merchants = task?.allowedMerchants.filter((m) => !m.archived) ?? [];

  function submit(e: FormEvent) {
    e.preventDefault();
    if (!task) return;
    simulate.mutate({
      policyVersionId: policy.id,
      taskId: task.id,
      merchantId: merchantId || merchants[0]?.id || '',
      amount: { currency: task.currency, value: amount.trim() },
    });
  }

  return (
    <Panel title="Test a purchase">
      <div className="space-y-4 px-5 py-4">
        {tasks.isPending ? (
          <Loading />
        ) : !tasks.data?.length ? (
          <p className="text-sm text-slate-600">
            Create an active{' '}
            <Link to="/tasks" className="underline">
              task
            </Link>{' '}
            to test purchases against this policy.
          </p>
        ) : (
          <form
            onSubmit={submit}
            className="grid gap-3 sm:grid-cols-[1fr_1fr_8rem_auto] sm:items-end"
          >
            <Field label="Task">
              {(id) => (
                <Select
                  id={id}
                  value={task?.id}
                  onChange={(e) => {
                    setTaskId(e.target.value);
                    setMerchantId('');
                  }}
                >
                  {tasks.data.map((t) => (
                    <option key={t.id} value={t.id}>
                      {t.instruction.slice(0, 60)}
                    </option>
                  ))}
                </Select>
              )}
            </Field>
            <Field label="Merchant">
              {(id) => (
                <Select
                  id={id}
                  value={merchantId || merchants[0]?.id}
                  onChange={(e) => setMerchantId(e.target.value)}
                >
                  {merchants.map((m) => (
                    <option key={m.id} value={m.id}>
                      {m.displayName}
                    </option>
                  ))}
                </Select>
              )}
            </Field>
            <Field label={`Amount (${task?.currency ?? ''})`}>
              {(id) => (
                <Input
                  id={id}
                  required
                  inputMode="decimal"
                  placeholder="25.00"
                  value={amount}
                  onChange={(e) => setAmount(e.target.value)}
                />
              )}
            </Field>
            <Button
              type="submit"
              variant="secondary"
              disabled={simulate.isPending || !merchants.length}
            >
              Test
            </Button>
          </form>
        )}
        <ErrorMessage error={simulate.error} />
        {simulate.data && <SimulationResult result={simulate.data} />}
      </div>
    </Panel>
  );
}

function SimulationResult({ result }: { result: SimulationResponse }) {
  const matched = result.results.filter((r) => r.matched);
  return (
    <div
      className="space-y-2 rounded-md bg-slate-50 p-4 text-sm ring-1 ring-inset ring-slate-200"
      role="status"
    >
      <p className="flex items-center gap-2 font-medium">
        Result: <DecisionPill decision={result.decision} />
      </p>
      {matched.length > 0 ? (
        <ul className="space-y-1">
          {matched.map((r) => (
            <li key={r.ruleId} className="flex gap-2">
              <StatusPill tone={r.action === 'BLOCK' ? 'error' : 'warn'}>{r.reasonCode}</StatusPill>
              <span className="text-slate-700">{r.detail}</span>
            </li>
          ))}
        </ul>
      ) : (
        <p className="text-slate-600">No rule matched.</p>
      )}
      <p className="text-xs text-slate-500">{result.note}</p>
    </div>
  );
}
